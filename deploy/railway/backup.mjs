import { spawn } from 'node:child_process';
import { createWriteStream, createReadStream } from 'node:fs';
import { stat, unlink } from 'node:fs/promises';
import { pipeline } from 'node:stream/promises';
import { createGzip } from 'node:zlib';
import { S3Client, PutObjectCommand, HeadObjectCommand } from '@aws-sdk/client-s3';
const required = ['DB_HOST','DB_PASSWORD','S3_ENDPOINT','S3_BUCKET','S3_ACCESS_KEY_ID','S3_SECRET_ACCESS_KEY'];
for (const key of required) if (!process.env[key]) throw new Error('Missing variable: '+key);
const file = '/tmp/bigcapital-backup.sql.gz';
const child = spawn('mariadb-dump', ['--host='+process.env.DB_HOST,'--user=root','--all-databases','--single-transaction','--routines','--events','--triggers','--hex-blob'], {env:{...process.env,MYSQL_PWD:process.env.DB_PASSWORD},stdio:['ignore','pipe','pipe']});
child.stderr.on('data', () => {});
const done = new Promise((resolve,reject) => { child.on('error',reject); child.on('close',code => code===0?resolve():reject(new Error('Database dump failed: '+code))); });
await Promise.all([pipeline(child.stdout,createGzip(),createWriteStream(file)), done]);
const size = (await stat(file)).size;
if (size < 100) throw new Error('Empty database backup');
const s3 = new S3Client({endpoint:process.env.S3_ENDPOINT,region:process.env.S3_REGION||'auto',credentials:{accessKeyId:process.env.S3_ACCESS_KEY_ID,secretAccessKey:process.env.S3_SECRET_ACCESS_KEY},forcePathStyle:false});
const key = 'database/'+new Date().toISOString().replaceAll(':','-')+'.sql.gz';
await s3.send(new PutObjectCommand({Bucket:process.env.S3_BUCKET,Key:key,Body:createReadStream(file),ContentLength:size,ContentType:'application/gzip'}));
const saved = await s3.send(new HeadObjectCommand({Bucket:process.env.S3_BUCKET,Key:key}));
if(saved.ContentLength!==size) throw new Error('Backup size check failed');
await unlink(file);
console.log(JSON.stringify({status:'backup_verified',key,bytes:size}));
